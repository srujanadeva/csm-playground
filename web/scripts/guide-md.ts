// Builds docs/user-guide.md from the guide data (web/src/modules/help/guide/flows.ts) and its
// English text (web/src/locales/en/help.json), so the Markdown guide and the in-app Help centre
// never drift apart. `--check` exits 1 when the committed file is out of date (used by npm run check).
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import * as prettier from 'prettier'
import { DEMO_LOGIN, FLOWS, PERSONAS, type GuideFlow, type Persona } from '../src/modules/help/guide/flows.ts'
import { LOCATOR_STYLES } from '../src/lib/locators.ts'

const ROOT = resolve(import.meta.dirname, '../..')
const OUT = resolve(ROOT, 'docs/user-guide.md')

/* eslint-disable @typescript-eslint/no-explicit-any -- untyped JSON text. */
const help: any = JSON.parse(readFileSync(resolve(ROOT, 'web/src/locales/en/help.json'), 'utf8'))
const ui: any = JSON.parse(readFileSync(resolve(ROOT, 'web/src/locales/en/ui.json'), 'utf8'))

/** Escapes characters that would break a Markdown table cell. */
const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ')

/** One flow as a Markdown section. */
function flowSection(f: GuideFlow, persona: Persona): string {
  const text = help.flows[f.id]
  const L = help.labels
  const login = DEMO_LOGIN[persona]
  const lines = [
    `### ${text.title}`,
    '',
    text.summary,
    '',
    `- **${L.who}:** ${f.personas.map((p) => help.personas[p].name).join(', ')}`,
    `- **${L.start}:** \`${f.route}\``,
    `- **${L.signIn}:** ${login ? `\`${login}\`` : L.notSignedIn}`,
    ...(f.samples?.length
      ? [`- **${L.samples}:** ${f.samples.map((s) => `\`testresources/${s}\``).join(', ')}`]
      : []),
    '',
    `**${L.steps}**`,
    '',
    ...(text.steps as string[]).map((s, i) => `${i + 1}. ${s}`),
    '',
    `**${L.expected}:** ${text.expected}`,
    '',
    `| ${L.element} | ${L.locator} | ${L.hint} |`,
    '| --- | --- | --- |',
    ...f.elements.map(
      (e) => `| ${cell(help.elements[e.key].name)} | \`${e.locator}\` | ${cell(help.elements[e.key].hint)} |`,
    ),
    '',
  ]
  return lines.join('\n')
}

/** The whole guide. Flows appear under their first persona, so nothing is listed twice. */
function build(): string {
  const parts = [
    `<!-- Generated by \`npm run guide:md\` from web/src/modules/help/guide and web/src/locales/en/help.json. Don't edit by hand. -->`,
    '',
    `# ${help.title}`,
    '',
    help.intro,
    '',
    `## ${help.gettingStarted.title}`,
    '',
    ...(help.gettingStarted.steps as string[]).map((s, i) => `${i + 1}. ${s}`),
    '',
    `### ${help.labels.locatorStyles}`,
    '',
    `| Code | ${help.labels.hint} |`,
    '| --- | --- |',
    ...LOCATOR_STYLES.map((s) => `| \`${s}\` | ${ui.locator[s]} |`),
    '',
  ]
  for (const p of PERSONAS) {
    const flows = FLOWS.filter((f) => f.personas[0] === p)
    if (!flows.length) continue
    parts.push(`## ${help.personas[p].name}`, '', help.personas[p].intro, '')
    for (const f of flows) parts.push(flowSection(f, p))
  }
  return parts.join('\n')
}

const config = (await prettier.resolveConfig(OUT)) ?? {}
const md = await prettier.format(build(), { ...config, parser: 'markdown' })

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(OUT, 'utf8')
  } catch {
    // Missing counts as out of date.
  }
  if (current !== md) {
    console.error('docs/user-guide.md is out of date. Run: npm run guide:md')
    process.exit(1)
  }
  console.log('docs/user-guide.md is up to date.')
} else {
  writeFileSync(OUT, md)
  console.log(`Wrote ${OUT}`)
}
